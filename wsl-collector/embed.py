#!/usr/bin/env python3
"""Regenerates src/wsl/collector_embed.cpp from collector.py. Run after editing the collector.

The bytes go into an unsigned char array: a byte of 128 or more in a plain char array would be a
narrowing conversion that MSVC rejects (docs/TODO.md item 10)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
data = open(os.path.join(here, "collector.py"), "rb").read()
rows = []
for i in range(0, len(data), 24):
    rows.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
out = ("// Generated by wsl-collector/embed.py from collector.py. Do not edit.\n"
       '#include "wsl/collector_embed.h"\n\nnamespace wwt {\nnamespace {\n'
       "const unsigned char kCollector[] = {\n" + "\n".join(rows) + "\n};\n}  // namespace\n\n"
       "const char* embedded_collector(size_t& size) {\n  size = sizeof kCollector;\n"
       "  return reinterpret_cast<const char*>(kCollector);\n}\n\n}  // namespace wwt\n")
open(os.path.join(here, "..", "src", "wsl", "collector_embed.cpp"), "w", newline="\n").write(out)
